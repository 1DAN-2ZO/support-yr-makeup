  it("모든 REGION_KEYS에 대해 3점 이상의 폴리곤을 만든다", () => {
    const regions = buildRegions(fakeLandmarks(), 100, 100);
    for (const key of REGION_KEYS) {
      expect(regions[key].length).toBeGreaterThanOrEqual(3);
    }
  });

