// 부위별 랜드마크 폴리곤 — poc/look-tryon/client/lib/regions.js 포팅 검증
import { describe, expect, it } from "vitest";
import { buildRegions, centroid, REGION_KEYS } from "@core/regions";
import type { Pt } from "@core/types";

function fakeLandmarks(n = 468): Pt[] {
  return Array.from({ length: n }, (_, i) => ({ x: (i % 10) / 10, y: (i % 7) / 7, z: 0 }));
}

