-- 앱에만 있던 것을 디비로 옮긴다 (2026-10-15)
--
-- 앱(client/src/core/product-picks.ts)이 손으로 들고 있던 것 가운데 **디비에 없는 것**을
-- 여기로 옮긴다. 옮기지 않으면 디비로 갈아끼울 때 그대로 사라진다.
--   ① 제품 사진 — 22줄 (파일 15개). 디비에 없던 것은 투에이엔 호수 사진 한 장뿐이었다
--   ② 「전지원이 직접 확인」 표시 — 앱의 `checked: true` 22줄 (product.checked 칸을 새로 만들었다)
--   ③ 앱이 호수 이름을 읽어서 적어 둔 계열 — 디비 호수로는 안 덮이는 것
--       (product_family 표. **ZZ3 파일에 있다** — 아래 ⑥ 참고)
--   ④ 퓌 치크칩 발색 네 색 — 앱 주석에만 있던 실측값이라 호수로 넣었다
--   ⑤ 클리오 팔레트 통 세 개 — 앱이 이름을 적어 둔 통인데 디비에 없었다
--
-- 제품 설명 글(kind)은 **앱과 디비가 글자까지 똑같았다** (19개 전부 대조). 옮길 것이 없다.
--
-- ───────────────────────────────────────────────────────────────────────────
-- 계열을 왜 product_family 로 넣나 — shade 에 못 넣는다
--
-- 앱의 계열 목록은 **호수 이름을 읽어서** 적은 것이다 ("호수에 그레이브라운·다크브라운·
-- 내추럴브라운·베이지애쉬·토프애쉬·밀키토프가 있어"). 그래서 계열은 아는데 **그 계열이
-- 어느 호수인지, 그 색이 무엇인지는 모른다.** shade 표에 넣으려면 호수 이름을 지어내야 한다.
-- 그래서 제품에 바로 붙이는 표를 하나 두었다 (schema.sql 의 product_family).
-- 호수 색을 재서 shade 에 넣으면 여기 줄을 지우면 된다.
--
-- 팔레트처럼 디비가 **통 단위로 쪼개 놓은** 제품은, 앱이 줄 하나에 적어 둔 계열이
-- 어느 통 것인지 앱에도 안 적혀 있다. 통 이름에 색 낱말이 든 것(「10 플럼 플럼 인 시즌」)은
-- 그 통에 붙였고, 아닌 것은 **호수가 아직 없는 첫 통**에 붙이고 note 에 그렇게 적었다.
-- 그 통이라고 확인한 것이 아니다 — 호수 색을 재면 맞는 통으로 옮겨야 한다.
-- ───────────────────────────────────────────────────────────────────────────

