--   아래에 '번호 이름' 이 적혀 있다.
--
-- **왜 MIX 인가**: 한 통에 색이 둘(A·B)인데 shade 한 줄에는 색을 하나만 적을 수 있다.
-- 둘을 섞어 바른 MIX 사진이 "이 호수를 쓰면 볼이 이렇게 된다" 에 가장 가깝다고 보고 그것을 썼다.
-- (A·B 를 따로 담으려면 섀도우 팔레트와 같은 설계 문제라 손대지 않았다.)
--
-- **뽑은 규칙**: 본 앱 client/src/core/ref-colors.ts 와 같다. MIX 사진에서 눈과 제품통을 피해
-- 볼만 들어가는 상자(x 650~980, 칸 시작 +250 부터 120px)를 잡고 Lab 밝기 cheek 구간
-- [30,80](가운데 밝기 — 주근깨와 하이라이트를 뺀다)만 남겨 RGB 평균.
-- 볼터치는 피부가 비쳐야 하므로 **피부 발색만 썼다** — 통 안 색이나 칩은 쓰지 않았다.
--
-- **말이 되는지 확인**: 색상각 차례가 이름과 맞는다.
--   16 핑크 텐션 358.8 · 01 코튼캔디 바이올렛 358.0 (가장 쿨)
--   09 하트 벌룬 3.6 · 13 베리 큐피드 10.6 · 17 버블 하트 10.9
--   03 코코 코랄 35.6 · 07 피치 피즈 38.6 · 12 오렌지 플레어 43.3 (가장 웜)
--
-- **그런데 전부 trust='doubt' 로 넣는다** — 두 가지 까닭이다.
--   ① 볼터치는 얇게 얹혀서 뽑은 색이 거의 피부색이다. 20색이 전부 L* 77~84 · 채도 16~33 안에
--      몰려 있어 호수끼리 거의 안 갈린다. 본 앱은 볼에 피부 걷어내기(unmixSkin)를 거는데,
--      기준이 될 맨 이마가 이 사진에 없어 못 걸었다.
--   ② 그래서 family 기준색(cheek 은 L* 62~75)과 범위 자체가 달라, 거리를 재면 밝은 쪽 계열로
--      쏠린다. 실제로 금을 넘은 4개가 모두 '피치' 로 나왔다.
--   **피부 걷어내기를 걸 수 있는 사진을 찾거나, family.ref_hex 를 "피부에 바른 색" 으로
--   다시 잡기 전에는 이 값으로 추천을 돌리지 않는 쪽이 좋다.**
--
