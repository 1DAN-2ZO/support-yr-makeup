INSERT INTO shade(product_id, code, name, family, part, hex, hex_source, hex_note, trust, checked)
SELECT p.id, v.code, v.name, v.family, 'cheek', v.hex, '발색사진', v.note, 'doubt', 0
FROM product p JOIN brand b ON b.id=p.brand_id AND b.name='투에이엔'
JOIN (
  -- 이름은 '코랄' 인데 피부에 바른 색은 밝아서 피치 기준색에 가깝다. 이름이 아니라 색을 따랐다
  SELECT '03' code, '코코 코랄'  name, '피치' family, '#f7b5a9' hex, '투에이엔 공식몰 상세 MIX 볼 사진 · cheek [30,80] · 피부 걷어내기 없음 · L* 79.6 으로 기준색(62~75)보다 밝다 · 피치 11.6 (2위 살구 15.6)' note UNION ALL
  SELECT '05', '무드 인 치크',      '피치', '#f7b6ac', '투에이엔 공식몰 상세 MIX 볼 사진 · cheek [30,80] · 피부 걷어내기 없음 · L* 79.7 로 기준색보다 밝다 · 피치 12.9 (2위 핑크 16.4)' UNION ALL
  SELECT '07', '피치 피즈',         '피치', '#f7baab', '투에이엔 공식몰 상세 MIX 볼 사진 · cheek [30,80] · 피부 걷어내기 없음 · L* 80.6 으로 기준색보다 밝다 · 피치 11.8 (2위 살구 16.0)' UNION ALL
  -- 이름은 '오렌지' 인데 cheek 계열에 오렌지가 없고, 색상각 43.3 은 피치·살구 사이다
  SELECT '12', '오렌지 플레어',      '피치', '#f9beab', '투에이엔 공식몰 상세 MIX 볼 사진 · cheek [30,80] · 피부 걷어내기 없음 · 이름은 오렌지인데 cheek 계열에 오렌지가 없다 · 피치 11.5 (2위 살구 15.7)'
) v
WHERE p.name='듀얼 치크';
