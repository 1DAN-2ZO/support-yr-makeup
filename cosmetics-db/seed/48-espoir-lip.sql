  SELECT '11', '버터 벨',           '레드',  '#ca5952', '에스쁘아 공식몰 Color Shade 입술 사진 · lip [40,85] · 피부 걷어내기 없음 · 상세 설명은 버터 베이지인데 사진 색은 레드 쪽(레드 7.0, 딥레드 11.6)' UNION ALL
