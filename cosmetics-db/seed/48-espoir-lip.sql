FROM product p JOIN brand b ON b.id=p.brand_id AND b.name='에스쁘아'
JOIN (
  SELECT '03' code, '칠링칠링'  name, '레드'   family, '#e2646b' hex, '에스쁘아 공식몰 Color Shade 입술 사진 · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 레드 13.2 (2위 코랄 17.6)' note UNION ALL
