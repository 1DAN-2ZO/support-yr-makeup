INSERT INTO shade(product_id, code, name, family, part, hex, hex_source, hex_note, trust, checked)
SELECT p.id, NULL, v.name, v.family, 'lip', v.hex, '발색사진', v.note, 'ok', 0
FROM product p JOIN brand b ON b.id=p.brand_id AND b.name='3CE'
JOIN (
  SELECT '웜스'        name, '피치' family, '#ec9b95' hex, '마켓컬리 상세의 브랜드 그림 입술 사진(#warmth) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 피치 9.0 (2위 누드베이지 13.5)' note UNION ALL
  -- 이름은 '코랄 문' 인데 뽑은 색은 레드 기준색에 더 가깝다(레드 10.8 vs 코랄 15.2). 규칙 쪽을 따른다
  SELECT '코랄 문',     '레드',  '#da5f5f', '마켓컬리 상세의 브랜드 그림 입술 사진(#coral moon) · lip [40,85] · 피부 걷어내기 없음 · 이름은 코랄인데 색은 레드 기준색에 더 가깝다(레드 10.8, 코랄 15.2)' UNION ALL
  -- '베이크 베이지' 도 이름은 베이지인데 색은 코랄 쪽이다
  SELECT '베이크 베이지', '코랄',  '#db7b71', '마켓컬리 상세의 브랜드 그림 입술 사진(#bake beige) · lip [40,85] · 피부 걷어내기 없음 · 이름은 베이지인데 색은 코랄 기준색에 가깝다(코랄 10.4, 피치 14.2)' UNION ALL
  SELECT '캐주얼 어페어', '레드',  '#c24e56', '마켓컬리 상세의 브랜드 그림 입술 사진(#casual affair) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 레드 5.7 (2위 딥레드 10.1)'
) v
WHERE p.name='블러 워터 틴트';
