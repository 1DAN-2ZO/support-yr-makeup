-- **다만**: 입술 사진에서 뽑은 색에는 모델의 입술 밑색이 섞여 있다. 본 앱은 립에
-- 피부 걷어내기(unmixSkin)를 거는데 여기서는 기준이 될 이마가 사진에 없어 못 걸었다.
-- 44-laka-lip-hex.sql 과 같은 한계다. 그래서 checked=0.
--
-- ───────────────────────────────────────────────────────────────────────────
-- **계열을 못 정해 안 넣은 호수 16개**
--
-- 계열은 이름으로 짐작하지 않고 **뽑은 색에서** 정했다 — family 표의 기준색 중 Lab 거리가
-- 가장 가까운 것. 다만 "가장 가까운 것이 1위와 2위가 거의 같으면" 찍는 것과 다를 바 없어서
-- **1위 거리 15 이하 + 2위와 3 이상 벌어질 때만** 넣었다.
--
-- 안 넣은 까닭은 대부분 **기준색이 제품 색인데 우리가 뽑은 것은 입술에 바른 색**이라서다.
-- 입술 밑색이 섞여 전체가 연해지는 바람에 어느 계열에도 딱 붙지 않는다. 이건 호수 하나의
-- 문제가 아니라 family.ref_hex 를 어떤 기준으로 둘 것인가의 문제라 혼자 정하지 않았다.
--
--   호수            뽑은 색    1위 계열(거리)   2위 계열(거리)
--   디어 마치        #db6d6d   레드 11.6       코랄 13.8
--   퍼스트 레터       #f2828b   핑크 13.8       로즈 14.1
