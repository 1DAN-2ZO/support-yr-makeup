-- **맞는지 확인한 방법**: 같은 상세가 호수를 COOL / NEUTRAL / WARM 세 칸으로 나눠 놓았는데,
-- 뽑은 색의 색상각이 그 칸 차례와 맞는다.
--   COOL  베리 잇 3.1 · 플럼 바이트 3.2 · 더블 윈드 13.9 · 나이트 토크 16.7 · 핑크 구아바 16.8 · 스팟 플레이어 17.7 · 얼리 아워 19.3
--   NEUT  퍼스트 레터 18.4 · 플레이 오프 22.5 · 디어 마치 25.1
--   WARM  레이다운 26.3 · 코랄 문 26.9 · 웜스 28.0 · 모어 피치 28.4 · 세피아 28.5 · 베이크 베이지 31.5 · 탱이 피버 34.9
--   (캐주얼 어페어 21.7 · 체이싱 로즈 24.1 · 인 더 나우 20.8 도 WARM 칸이라 이 둘만 어긋난다)
