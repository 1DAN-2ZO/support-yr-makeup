-- 에뛰드 드로잉 아이 브라우 — 6색 (2026-10-14)
--
-- 호수 목록이 세 세대로 갈려 앞서 넣지 못했던 제품이다.
--   ① 6색: 1 흑갈색 · 2 회갈색 · 3 갈색 · 4 차콜그레이 · 5 그레이 · 6 블랙
--   ② 7색: 01 다크브라운 … 07 라이트브라운
--   ③ 「드로잉 아이브로우 **프로**」 — ②와 같은 7색. **후속 제품이라 다른 것**이다
--
-- **①로 정했다.** 언니의파우치의 "드로잉 아이 브라우" 리뷰가 1호 흑갈색·2호 회갈색·3호 갈색으로
-- ①과 맞고, DB 의 제품 이름도 「드로잉 아이 브라우」(프로 아님)다. 공식몰에는 이 이름이
-- 남아 있지 않아 확정은 못 했다 — 틀렸다면 이 파일만 빼면 된다.
--
-- 색 출처: 스타일코리안에 실린 브랜드 상세 그림의 **종이 발색**
--   https://d2c3d01lcpw2ui.cloudfront.net/gl/data/editor/1708/09707e1b36e6a27d1287844f09674c59_1504159084_9845.jpg
-- 뽑는 규칙은 본 앱 ref-colors 의 brow [5,35]. 종이 발색이라 어두운 쪽이 안 들렸다.
-- 맞는지 확인: 밝기·채도 차례가 이름과 맞는다 — 6 블랙이 가장 어둡고(L* 13.6),
-- 5 그레이가 채도 3.2 로 가장 무채색이다.
--
-- 계열은 **브랜드가 붙인 호수 이름**을 따랐다. 색으로 정하지 않은 까닭은, 눈썹 계열의
-- 기준색이 아직 제품 색이라(호수가 3개 미만이라 못 고쳤다) 색으로 재면 엉뚱하게 붙기 때문이다.

INSERT INTO shade(product_id, code, name, family, part, hex, hex_source, hex_note, trust, checked)
SELECT p.id, v.code, v.name, v.family, 'brow', v.hex, '종이발색', v.note, 'ok', 0
FROM product p JOIN brand b ON b.id=p.brand_id AND b.name='에뛰드'
JOIN (SELECT '1' code, '흑갈색'     name, '다크브라운'  family, '#543427' hex, '종이 발색 · L* 25.3' note UNION ALL
      SELECT '2',      '회갈색',          '그레이브라운', '#4a4139', '종이 발색 · L* 28.1'  UNION ALL
      SELECT '3',      '갈색',            '브라운',      '#4a3124', '종이 발색 · L* 23.0'  UNION ALL
      SELECT '4',      '차콜그레이',       '그레이브라운', '#453c3b', '종이 발색 · L* 26.2'  UNION ALL
      SELECT '5',      '그레이',          '그레이브라운', '#5a5351', '종이 발색 · L* 35.8 · 채도 3.2 로 가장 무채색' UNION ALL
      SELECT '6',      '블랙',            '소프트블랙',   '#29211f', '종이 발색 · L* 13.6 · 가장 어둡다') v
WHERE p.name='드로잉 아이 브라우';
