-- 롬앤 쥬시 래스팅 틴트 — 호수와 색 (2026-10-14)
--
-- **이름이 어긋난다**: DB 의 제품 이름은 '쥬시 래스팅 틴트' 인데, 롬앤 공식몰에서 지금 파는 것은
-- **'더 쥬시 래스팅 틴트'** 다(romand.co.kr 검색 14건 중 '더' 가 안 붙은 것은 코덕MADE 미니뿐).
-- 리뉴얼로 보여 같은 제품으로 다뤘다. 아니라면 이 파일을 통째로 빼면 된다.
--
-- 출처: 롬앤 공식몰 상세의 **COLOR CHART — 입술에 바른 사진**
--   https://romand.co.kr/product/롬앤-더-쥬시-래스팅-틴트/958/
--   그림 .../web/upload/NNEditor/20241118/더 쥬시 래스팅 틴트_24.jpg (900x10261) — THE NUDE · THE MLBB
--        .../web/upload/NNEditor/20241118/더 쥬시 래스팅 틴트_25.jpg (900x15639) — THE CORAL · THE PINKRED · THE BRICK
--   한 줄이 [왼쪽: 바르는 사진][가운데: 입술만][오른쪽: 제형] 이고 그 아래 '번호 이름' 이 적혀 있다.
--
-- **뽑은 규칙**: 본 앱 client/src/core/ref-colors.ts 와 같다. 가운데 입술 사진에 상자
-- (x 450~700, 줄 시작 +55 부터 145px)를 잡고 Lab 밝기 lip 구간 [40,85] 만 남겨 RGB 평균.
-- 광택 틴트라 번들거림이 섞이는데, [40,85] 의 위쪽 잘라내기가 그 반짝임을 뺀다.
-- 입술은 피부가 비쳐야 하므로 **피부 발색만 썼다**.
--
-- **이름으로 계열을 짐작하지 않았다** — '누카다미아' '잇 도토리' 처럼 이름만으로는 계열을 알 수
-- 없어서 앞서 한 사람이 포기한 제품이다. 그래서 **색을 먼저 뽑고 그 색으로** 정했다.
--
-- **맞는지 확인한 방법**: 상세가 호수를 NUDE / MLBB / CORAL / PINKRED / BRICK 다섯 칸으로
-- 나눠 놓았는데, 뽑은 색의 색상각이 그 칸 차례와 맞는다.
--   NUDE    33.6~38.7 (밝다, L* 63~66)
--   MLBB    12.5~25.8 (L* 52~63)
--   CORAL   24.6~32.6
--   PINKRED 11.1~23.1 (가장 어둡다 — 16 플럼 콕 L* 36.5)
--   BRICK   27.0~41.6 (12 애플 브라운이 41.6 으로 가장 주황 쪽)
--
-- **다만**: 입술 밑색이 섞여 있고, 기준이 될 이마가 사진에 없어 피부 걷어내기(unmixSkin)를
-- 못 걸었다. 44-laka-lip-hex.sql 과 같은 한계다. checked=0.
--
-- ───────────────────────────────────────────────────────────────────────────
-- **계열을 못 정해 안 넣은 호수 14개**
--
-- 계열은 family 표 기준색 중 Lab 거리가 가장 가까운 것으로 정하되, **1위 거리 15 이하 +
-- 2위와 3 이상 벌어질 때만** 넣었다. 아래는 1·2위가 거의 붙어 있어 찍는 것과 다를 바 없는 것들이다.
--
--   호수               뽑은 색    1위 계열(거리)   2위 계열(거리)
--   01 포멜로 스킨      #d78e7f   피치 6.2        누드베이지 7.9
--   02 누카다미아       #d5867a   피치 8.9        누드베이지 10.9
--   24 베어 쥬시 오     #de8773   피치 8.6        코랄 9.9
--   03 베어 그레이프     #d78183   로즈 11.1       핑크 11.2
--   08 핑크 펌킨       #d26257   레드 9.7        코랄 10.5
--   09 멀드 피치       #cd7c73   피치 12.6       누드베이지 13.2
--   11 파파야 잼       #db7068   코랄 9.8        레드 12.2
--   23 피치 피치 미     #e48b89   피치 12.2       핑크 13.8
--   06 필링 앵두       #bc6062   레드 8.5        로즈 10.9
--   07 체리 밤        #b53945   딥레드 6.8      레드 9.7
--   16 플럼 콕        #9d2a49   버건디 14.9     플럼 16.1
--   19 썸머 센트       #d34151   딥레드 15.7     레드 16.2
--   21 그레이프 밤      #c85669   로즈 10.8       레드 11.5
--   13 잇 도토리       #b34c3b   브릭 8.7        딥레드 9.0
-- ───────────────────────────────────────────────────────────────────────────

INSERT INTO shade(product_id, code, name, family, part, hex, hex_source, hex_note, trust, checked)
SELECT p.id, v.code, v.name, v.family, 'lip', v.hex, '발색사진', v.note, 'ok', 0
FROM product p JOIN brand b ON b.id=p.brand_id AND b.name='롬앤'
JOIN (
  SELECT '04' code, '피그 피그'    name, '로즈' family, '#c0656d' hex, '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE MLBB) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 로즈 6.7 (2위 레드 12.2)' note UNION ALL
  -- 상세 설명은 '코랄 MLBB' 라고 하는데 뽑은 색은 레드 기준색에 가깝다. 이름이 아니라 색을 따랐다
  SELECT '05', '쥬쥬브',          '레드', '#cb6867', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE MLBB) · lip [40,85] · 피부 걷어내기 없음 · 상세 설명은 코랄 MLBB 인데 색은 레드 기준색에 가깝다(레드 9.1, 로즈 12.3)' UNION ALL
  SELECT '10', '베어 애프리콧',     '코랄', '#e67872', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE CORAL) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 코랄 10.7 (2위 레드 15.3)' UNION ALL
  SELECT '12', '애플 브라운',      '코랄', '#cd664a', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE BRICK) · lip [40,85] · 피부 걷어내기 없음 · 이름은 브라운인데 색상각 41.6 으로 코랄 기준색에 가깝다(코랄 7.6, 오렌지 11.1)' UNION ALL
  SELECT '14', '아몬드 로즈',      '로즈', '#bd6e6d', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE MLBB) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 로즈 11.3 (2위 레드 15.1)' UNION ALL
  SELECT '15', '베어 피그',        '로즈', '#b76572', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE MLBB) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 로즈 6.4 (2위 핑크 12.3)' UNION ALL
  SELECT '17', '다크 코코넛',      '브릭', '#ac5c4f', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE BRICK) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 브릭 6.2 (2위 레드 10.8)' UNION ALL
  SELECT '20', '쥬쥬 피그',        '로즈', '#cc7072', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE MLBB) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 로즈 9.2 (2위 레드 13.2)' UNION ALL
  SELECT '22', '도토리 밤',        '레드', '#b64c4c', '롬앤 공식몰 상세 COLOR CHART 입술 사진(THE BRICK) · lip [40,85] · 피부 걷어내기 없음 · 계열 거리 레드 1.5 (2위 딥레드 6.9)'
) v
WHERE p.name='쥬시 래스팅 틴트';
