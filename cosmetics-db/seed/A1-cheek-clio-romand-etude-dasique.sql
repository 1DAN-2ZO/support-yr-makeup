-- 볼터치 호수와 색 — 롬앤 · 데이지크 (2026-10-15)
--
-- 맡은 브랜드는 클리오 · 롬앤 · 에뛰드 · 데이지크 넷이었는데, **발색 사진을 찾은 둘만** 넣었다.
-- 클리오와 에뛰드는 공식몰에서 피부 발색 사진을 못 찾아 **한 호수도 안 넣었다** (아래 ③).
--
-- ───────────────────────────────────────────────────────────────────────────
-- ① 색을 어디서 읽었나 — 색상칩이 아니라 **피부에 바른 발색 사진**
--
-- 통 안(팬) 색과 쇼핑몰 색상칩은 쓰지 않았다. 이 디비의 hex 는 사용자 사진에서 읽은
-- "피부 위 색" 과 견주는 값이라, 조건이 같아야 비교가 된다 (45·49 파일과 같은 결정).
--
-- 뽑는 규칙: 바른 자리 한가운데에 **21x21 패치를 잡아 RGB 채널별 중앙값**을 썼다.
-- 한 점만 찍으면 조명 얼룩·압축 잡티에 휘둘려서 패치 중앙값으로 했다.
-- 같은 사진 안의 **맨살**도 같이 재서 hex_note 에 적어 두었다 — 사진마다 조명이 다르므로
-- 나중에 보정하려면 그 값이 있어야 한다.
--
-- ② 계열(family) 을 넣은 까닭 — **원래는 비워 두라고 했는데 못 비웠다**
--
-- 받은 지시는 "family 는 NULL 로 두고 앱 함수(99-family-from-app-name.sql)가 정하게 하라"
-- 였다. 그런데 **그렇게 할 수가 없었다.** 두 가지가 막는다.
--   ⑴ schema.sql 의 `family TEXT NOT NULL` — NULL 을 넣으면 build.py 가 그 자리에서 깨진다
--      (직접 넣어 보고 확인했다: "NOT NULL constraint failed: shade.family").
--   ⑵ 파일 이름이 'A1' 이라 **99 번 파일보다 늦게** 들어온다(숫자 < 영문). 게다가 99 번은
--      `UPDATE shade SET family=... WHERE id=1` 처럼 **id 를 박아 둔 한 번짜리 손질**이라,
--      순서를 뒤집어도 여기 새 호수에는 닿지 않는다.
--
-- 그래서 **이름을 내가 짓는 대신, 앱이 쓰는 그 함수를 그대로 돌려서** 나온 이름을 넣었다.
-- client/src/core/color-name.ts 의 cheek 규칙(ZONES·special·GRAY_C)을 값 하나 안 바꾸고
-- 파이썬으로 옮겨 뽑은 결과다. 99 번 파일이 하던 일과 같은 함수·같은 값이다.
-- **사람이 금을 긋지 않았다.** 그래도 지시와 다르니, 다른 방식을 원하면 이 파일만 고치면 된다.
--
-- 여기서 나온 계열은 베이지핑크 · 모브 · 로즈 셋뿐이고 전부 family 표에 이미 있다.
-- 새 계열을 만들지 않았다. 쏠리는 까닭은 cheek 의 special 규칙
-- (`채도<28 이고 색상각 30~56 이면 베이지핑크`) 인데, 볼터치를 피부에 얇게 바르면
-- 거의 다 이 구간에 들어간다. 49-2an-cheek.sql 이 적어 둔 문제와 같은 것이다.
--
-- ③ 못 넣은 브랜드
--   클리오 — 공식몰(클럽클리오)에서 **클리오 브랜드 볼터치 자체를 못 찾았다.** 사이트맵
--     319개에 치크는 페리페라 '맑게 물든 선샤인 치크' 둘뿐이고(이미 디비에 있는 제품),
--     치크/컨투어링 분류 페이지는 자바스크립트로 그려서 그냥 받으면 기본 목록만 온다.
--     옛 리뷰에 '프리즘 에어 블러셔 001 뮤티드 핑크' 가 보이지만 **단종인지는 확인 못 했다.**
--     공식몰에 안 보인다는 것만으로 단종이라고 적지 않는다.
--   에뛰드 — 제품은 찾았다(벌룬 인 치크 6색: 버블 라벤더·베베 요거트·왓 어 베이지·
--     점핑 쿨·조이 코랄·캔디 핑크 / 프루티 립앤치크 블러밤 5색 / 하트팝 블러셔).
--     그런데 etude.com 은 워드프레스 브랜드 사이트라 **상품 사진이 통 사진뿐**이고,
--     호수별 피부 발색 사진이 없다. 모델 사진은 있으나 어느 호수인지 적혀 있지 않고
--     배경이 하늘색이라 색이 틀어져서 쓰지 않았다.
--
-- ④ 비어 있던 쪽을 메꿨나
--   코랄·살구 쪽 — 롬앤 C03 피그 칩·C04 페어 칩·N01 너티 누드가 색상각 39~46 으로 들어왔다.
